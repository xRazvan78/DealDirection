// API types, taken from TEAM_TASKS.md. Money and quantities are strings, so they
// never pass through a float.
//
// TEAM_TASKS.md doesn't define the types marked "Assumed", so confirm them with
// Member 2 when the route is built.

export interface Credentials {
  email: string;
  password: string;
}

export interface AuthResponse {
  token: string;
}

// Assumed: the fields, and `selected` for the client's store selection.
export interface Store {
  id: number;
  name: string;
  colour: string;
  logo: string | null;
  selected: boolean;
}

export interface Directions {
  address: string;
  maps_url: string;
}

// One branch of each store, in the order to visit them. `km` is the straight-line
// distance from the stop before, or from the client; null for a first stop
// when the location wasn't shared.
export interface RouteStop {
  store_id: number;
  store_name: string;
  address: string;
  lat: number;
  lng: number;
  km: number | null;
}

export interface ShoppingRoute {
  stops: RouteStop[];
  total_km: number;
  maps_url: string;
}

// Assumed.
export interface Category {
  id: number;
  parent_id: number | null;
  name: string;
  level: 'category' | 'type' | 'size';
}

export interface Product {
  id: number;
  store_id: number;
  store_name: string;
  name: string;
  brand: string | null;
  price: string;
  image_url: string | null;
  updated_at: string;
}

// Assumed: `generic` has the same fields as a product.
export interface CategoryProducts {
  generic: Product | null;
  products: Product[];
}

export interface SearchResult {
  size_category_id: number;
  path: string;
  generic: Product | null;
}

export type ListState = 'draft' | 'active' | 'completed';

// Assumed.
export interface ListItem {
  id: number;
  size_category_id: number;
  chosen_product_id: number | null;
  brand: string | null;
  quantity: string;
  removed: boolean;
}

// Assumed.
export interface ShoppingList {
  id: number;
  name: string;
  state: ListState;
  items: ListItem[];
}

export interface NewListItem {
  size_category_id: number;
  quantity: string;
  chosen_product_id?: number;
}

export interface Resolution {
  item_id: number;
  store_id: number;
  replacement_product_id: number | null;
}

// Assumed: follows the optimiser's dataclasses in Task 3.
export interface Assignment {
  item_id: number;
  store_id: number;
  offer: Product;
  line_total: string;
}

export interface Plan {
  kind: 'single' | 'split';
  total: string;
  assignments: Assignment[];
}

export interface MissingItem {
  item_id: number;
  store_id: number;
  options: Product[];
}

export interface Suggestion {
  store_id: number;
  saving: string;
}

export interface PlanResult {
  single: Plan | null;
  split: Plan | null;
  split_saving: string;
  missing: MissingItem[];
  unavailable: number[];
  suggestion: Suggestion | null;
}

export interface ListPart {
  store_id: number;
  store_name: string;
  items: ListItem[];
  estimate: string;
  receipt_done: boolean;
}

// Assumed: the fields inside `matched` and `unmatched_items`.
export interface ReceiptResult {
  matched: { name: string; line_total: string }[];
  unmatched_items: { name: string }[];
  estimate: string;
  paid: string;
  modifier: string;
  points: number;
}

// What a receipt says. A field OCR couldn't read is null.
export interface ReceiptReading {
  store_name: string | null;
  purchased_at: string | null;
  identifier: string | null;
  identifier_printed: boolean; // false: not on the receipt, generated by the app
  total: string | null;
  deposits: string; // bottle deposits: part of the total, but not products
  lines: { name: string; quantity: string; line_total: string }[];
}

// A list as the backend stores it. `items` and `receipt` are kept as the device sent them.
export interface StoredList {
  id: number;
  name: string;
  items: unknown[];
  updated_at: string;
  receipt: ReceiptReading | null;
  points: number | null;
}

// The cart's products, sent with the photo when a receipt is accepted.
export interface AcceptedItem {
  name: string;
  quantity: string;
  price: string;
}

export interface ImportPreview {
  items: { food: string; size_category_id: number; path: string; packs: number }[];
  unmapped: string[];
}

export interface ImportConfirmation {
  name: string;
  items: { size_category_id: number; packs: number }[];
}

export interface Wallet {
  balance: number;
  history: { amount: number; reason: string; created_at: string }[];
}

// Assumed: added for the voucher design, so the backend doesn't return it yet.
export interface Voucher {
  id: number;
  code: string;
  reward_name: string;
  store_name: string;
  expires_at: string;
}

export interface Reward {
  id: number;
  name: string;
  cost: number;
  store_name: string;
}

// Assumed.
// A supermarket a loyalty card can belong to (separate from price-comparison stores).
export interface CardBrand {
  id: string;
  name: string;
  colour: string;
}

// A code read from a card's photo; nothing is saved yet.
export interface CardScan {
  code_text: string;
  code_format: string;
  image: string; // data URI of the redrawn code
  suggested_brand: string | null;
}

export interface LoyaltyCard {
  id: number;
  brand: string;
  name: string;
  colour: string;
  code_text: string | null; // null when only a photo could be saved
  code_format: string | null;
  image: string; // data URI: the redrawn code, or the saved photo
}
